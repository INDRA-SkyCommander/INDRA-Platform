def _calcCRC16(data):
    crc = 0x3692
    for b in data: 
        crc = (crc >> 8) ^ CRC16_TABLE[(crc ^ b) & 0xFF]
    return crc

def _calcCRC8(data):
    crc = 0x77
    for b in data: 
        crc = CRC8_TABLE[(crc ^ b) & 0xFF]
    return crc

