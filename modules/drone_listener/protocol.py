def parse_stick(payload):
    val = int.from_bytes(payload[:6], 'little')
    
    roll      = (val >> 0) & 0x7FF
    pitch     = (val >> 11) & 0x7FF
    throttle  = (val >> 22) & 0x7FF
    yaw       = (val >> 33) & 0x7FF
    fast_mode = (val >> 44) & 0x7FF

    return {
        "roll": roll,
        "pitch": pitch,
        "throttle": throttle,
        "yaw": yaw,
        "fast_mode": fast_mode
    }

def parse_packet(data):
    """Parse a Tello binary packet. Returns a dict with parsed fields."""

    # Check min length and SOP byte
    if len(data) < 11 or data[0] != 0xCC:
        # Not a binary Tello packet - try parsing as plain text command
        text = data.decode(errors='replace').strip()
        return {"type": "text", "raw": text}
    
    size = struct.unpack_from('<H', data, 1)[0] >> 3 # Upper 13 bits
    crc8 = data[3]
    pkt_type = data[4]
    cmd_id = struct.unpack_from('<H', data, 5)[0]
    seq_id = struct.unpack_from('<H', data, 7)[0]
    payload = data[9:-2] 
    crc16 = struct.unpack_from('<H', data, len(data)-2)[0]

    from_drone = bool(pkt_type & 0x80)
    cmd_name = CMD_NAMES.get(cmd_id, f"Unknown({cmd_id})")

    result = {
        "type": "binary",
        "from_drone": from_drone,
        "direction": "DRONE->APP" if from_drone else "APP->DRONE",
        "cmd_id": cmd_id,
        "cmd_name": cmd_name,
        "seq_id": seq_id,
        "pkt_type": hex(pkt_type),
        "payload": payload.hex(),
    }

    # Decode known payloads
    if cmd_id == 80:  # STICK command
        result["stick"] = parse_stick(payload)
    elif cmd_id == 70: # DATE_TIME
        if len(payload) >= 10:
            result["datetime"] = {
                "year":   struct.unpack_from('<H', payload, 0)[0],
                "month":  struct.unpack_from('<H', payload, 2)[0],
                "day":    struct.unpack_from('<H', payload, 4)[0],
                "hour":   struct.unpack_from('<H', payload, 6)[0],
                "minute": struct.unpack_from('<H', payload, 8)[0],
            }

    return result

def parse_sdk_command(raw):
    """
    Parses a raw drone command string and returns a human-readable label.
    Handles both bare commands and commands with arguments (e.g. 'up 50').
    """
    raw = raw.strip().lower()
    base = raw.split()[0] if raw else ""

    if base in SDK_DRONE_COMMANDS:
        label = SDK_DRONE_COMMANDS[base]
        args = raw[len(base):].strip()
        return f"{label} {f'-> args: {args}' if args else ''}"
    
    return f"Unknown command: '{raw}'"

# Packet type constants
PKT_TYPE_DATA_EXT   = 0x60 # to drone, no ACK required
PKT_TYPE_DATA       = 0x68 # to drone, ACK required
PKT_TYPE_RESPONSE   = 0x50 # from drone, (response to command)
PKT_TYPE_FROM_DRONE = 0xC8 # from drone, (unsolicited)

def build_packet(cmd_id, payload=b'', pkt_type=PKT_TYPE_RESPONSE, seq_id=0): 
    total_len = len(payload) + 11

    # Build the first 3 bytes so we can compute CRC8 over them
    pre_cr8 = struct.pack('BH', 0xCC, total_len << 3)
    crc8 = _calcCRC8(pre_cr8)

    # Build the full packet without CRC16
    packet = struct.pack('<BHBBHH',
         0xCC, 
         total_len << 3, 
         crc8,
         pkt_type,
         cmd_id,
         seq_id,
    ) + payload
    
    # Append CRC16 over the entire packet so far
    crc16 = _calcCRC16(packet)
    packet += struct.pack('<H', crc16)

    return packet
    